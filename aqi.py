import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.model_selection import learning_curve

from sklearn.metrics import accuracy_score
from sklearn.metrics import confusion_matrix
from sklearn.metrics import classification_report
from sklearn.metrics import mean_squared_error, r2_score

"""##**Load dataset**"""

df = pd.read_csv("aqi5.csv")
df.head()

"""##**Data pre processing**"""

df.info()
df.shape

df.isnull().sum()

num_cols = df.select_dtypes(include=['float64','int64']).columns

for col in num_cols:
    df[col].fillna(df[col].mean(), inplace=True)

df = df.drop_duplicates()

if "City" in df.columns:
    df = df.drop(columns=["City"])

df.info()
df.shape

"""##**Select features and targets**"""

X = df[["PM2.5","PM10","NO2","SO2","CO","O3"]]
y_reg = df["AQI"]
y_cls = df["AQI_Category"]

"""##**Train-test split**"""

X_train, X_test, y_train_reg, y_test_reg, y_train_cls, y_test_cls = train_test_split(X, y_reg, y_cls, test_size=0.2, random_state=42)

"""##**Training regression model**"""

reg_model = RandomForestRegressor(random_state=42)
reg_model.fit(X_train, y_train_reg)

"""##**Regression results**"""

y_pred_reg = reg_model.predict(X_test)
rmse = np.sqrt(mean_squared_error(y_test_reg, y_pred_reg))
r2 = r2_score(y_test_reg, y_pred_reg)

print("RMSE:", rmse)
print("R2 Score:", r2)

"""##**Comparison of actual vs predicted AQI values**"""

plt.figure(figsize=(6,6))
plt.scatter(y_test_reg, y_pred_reg)
plt.xlabel("Actual AQI")
plt.ylabel("Predicted AQI")
plt.title("Actual vs Predicted AQI")

plt.show()

"""##**Train classification model**"""

clf_model = RandomForestClassifier(random_state=42)
clf_model.fit(X_train, y_train_cls)

"""##**Training accuracy score**"""

train_pred = clf_model.predict(X_train)
train_accuracy = accuracy_score(y_train_cls, train_pred)

print("Training Accuracy:", train_accuracy)

"""##**Testing accuracy score**"""

test_pred = clf_model.predict(X_test)
test_accuracy = accuracy_score(y_test_cls, test_pred)

print("Testing Accuracy:", test_accuracy)

"""##**Testing accuracy graph**"""

train_sizes, train_scores, test_scores = learning_curve(clf_model,X,y_cls,cv=5,scoring="accuracy",train_sizes=np.linspace(0.1, 1.0, 10),random_state=42)

train_mean = np.mean(train_scores, axis=1)
test_mean = np.mean(test_scores, axis=1)

plt.figure(figsize=(8,5))
plt.plot(train_sizes, train_mean, marker='o', label="Training Accuracy")
plt.plot(train_sizes, test_mean, marker='s', label="Testing Accuracy")
plt.xlabel("Training Data Size")
plt.ylabel("Accuracy")
plt.title("Learning Curve")
plt.legend()
plt.grid(True)

plt.show()

"""##**Confusion matrix**"""

cm = confusion_matrix(y_test_cls, test_pred)
print(cm)

cm = confusion_matrix(y_test_cls, test_pred)

plt.figure(figsize=(7,5))

sns.heatmap(cm, annot=True, cmap="Blues", fmt="d", xticklabels=clf_model.classes_, yticklabels=clf_model.classes_)

plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("Confusion Matrix")

plt.show()

print("Training data: ",X_train.shape)
print("Testing data: ",X_test.shape)

"""##**Classification scores**"""

test_pred = clf_model.predict(X_test)

print("Classification Report:\n")
print(classification_report(y_test_cls, test_pred))

importance = reg_model.feature_importances_
features = X.columns
plt.figure(figsize=(8,4))
sns.barplot(x=importance, y=features)
plt.title("Feature Importance for AQI Prediction")

plt.show()

plt.figure(figsize=(8,6))
correlation = df[["PM2.5","PM10","NO2","SO2","CO","O3","AQI"]].corr()
sns.heatmap(correlation, annot=True, cmap="coolwarm")
plt.title("Correlation Heatmap of Pollutants and AQI")

plt.show()

plt.figure(figsize=(7,5))
sns.countplot(x="AQI_Category", data=df)
plt.title("Distribution of AQI Categories")
plt.xlabel("AQI Category")
plt.ylabel("Number of Cities")
plt.xticks(rotation=30)

plt.show()

new_city = pd.DataFrame({"PM2.5":[40], "PM10":[100], "NO2":[40], "SO2":[12], "CO":[1.2], "O3":[35]})

predicted_aqi = reg_model.predict(new_city)
predicted_category = clf_model.predict(new_city)

